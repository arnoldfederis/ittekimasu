#!/usr/bin/env bun
/**
 * Render every icon the product ships, from the mark in `src/constants/brand-mark.ts`.
 *
 *   bun run icons              # both repos
 *   bun run icons -- --mobile  # apps/mobile only
 *
 * Covers the app (the iOS Icon Composer layer, the Android adaptive trio, the splash tile,
 * the web favicon) and the marketing site (favicons, the .ico, the Apple touch icon, the
 * PWA icons, and the square logo that opengraph-image.tsx, twitter-image.tsx and the
 * JSON-LD Organization all read off disk).
 *
 * Why a script and not twenty files someone exported once: the site's icon set shipped for
 * months as a different project's logo — byte-identical across favicon.ico,
 * apple-touch-icon and the OG card — because nothing said which of them were stale.
 * Deriving all of them makes "the mark changed" one edit and a re-run.
 *
 * Run with **Bun**, not Node: it imports the app's TypeScript constants directly, which is
 * what keeps the rendered icons and the runtime <ToriiMark> from drifting apart.
 *
 * The site is a SEPARATE checkout (~/Projects/ittekimasu-site). Set SITE_DIR if yours lives
 * elsewhere; the site half is skipped, not failed, when it is not there.
 */

import { mkdir, readdir, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import {
  ANDROID_SAFE_SCALE,
  MARK_COLORS,
  SQUIRCLE_RADIUS,
} from "../src/constants/brand-mark.ts";
import { solidSquare, svgDocument } from "./brand-svg.mjs";

const MOBILE_DIR = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SITE_DIR =
  process.env.SITE_DIR ?? resolve(MOBILE_DIR, "../../../ittekimasu-site");

/** Full-bleed square: the icon as the App Store and every favicon shows it. */
const SQUARE = svgDocument({ background: MARK_COLORS.teal });

/** The same tile, pre-masked, for the one place nothing else rounds it. */
const ROUNDED = svgDocument({
  background: MARK_COLORS.teal,
  clipRadius: SQUIRCLE_RADIUS,
});

/** Foreground only, transparent — Icon Composer and Android draw their own ground. */
const FOREGROUND = svgDocument({
  comment: [
    "The Ittekimasu mark, foreground ONLY — a layer for Icon Composer, which draws the",
    "  ground itself from `fill` in icon.json and derives the light, dark, tinted and clear",
    "  appearances from this one artwork. A baked-in background would defeat all four.",
    "",
    "  Generated by apps/mobile/scripts/generate-brand-assets.mjs — do not edit by hand.",
  ].join("\n  "),
});

const ANDROID_FOREGROUND = svgDocument({ scale: ANDROID_SAFE_SCALE });

/** Android's themed icon keeps alpha and throws the colour away, so one tone is enough. */
const ANDROID_MONOCHROME = svgDocument({
  scale: ANDROID_SAFE_SCALE,
  ink: { gate: "#000000", check: "#000000" },
});

const ANDROID_BACKGROUND = solidSquare(MARK_COLORS.teal);

/** Maskable PWA icon: the same safe zone as Android, over the brand ground. */
const MASKABLE = svgDocument({
  background: MARK_COLORS.teal,
  scale: ANDROID_SAFE_SCALE,
});

async function png(svg, size, out) {
  await mkdir(dirname(out), { recursive: true });
  await sharp(Buffer.from(svg))
    .resize(size, size, {
      fit: "contain",
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    })
    .png({ compressionLevel: 9 })
    .toFile(out);
  return out;
}

/**
 * Pack PNGs into an .ico: a 6-byte header, one 16-byte directory entry per image, then the
 * payloads.
 *
 * sharp cannot write ICO, and the alternative — a BMP encoder with its upside-down rows and
 * its AND mask — is far more code aimed at browsers older than this site will ever serve.
 * Every browser since Vista reads PNG-compressed entries.
 */
function buildIco(images) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0); // reserved
  header.writeUInt16LE(1, 2); // type: icon
  header.writeUInt16LE(images.length, 4);

  let offset = 6 + images.length * 16;
  const entries = [];

  for (const { size, data } of images) {
    const entry = Buffer.alloc(16);
    // The width and height fields are a single byte each; 256 is encoded as 0.
    entry.writeUInt8(size >= 256 ? 0 : size, 0);
    entry.writeUInt8(size >= 256 ? 0 : size, 1);
    entry.writeUInt8(0, 2); // palette colours
    entry.writeUInt8(0, 3); // reserved
    entry.writeUInt16LE(1, 4); // colour planes
    entry.writeUInt16LE(32, 6); // bits per pixel
    entry.writeUInt32LE(data.length, 8);
    entry.writeUInt32LE(offset, 12);
    entries.push(entry);
    offset += data.length;
  }

  return Buffer.concat([header, ...entries, ...images.map((i) => i.data)]);
}

async function writeIco(sizes, out) {
  const images = await Promise.all(
    sizes.map(async (size) => ({
      size,
      data: await sharp(Buffer.from(SQUARE)).resize(size, size).png().toBuffer(),
    })),
  );
  await mkdir(dirname(out), { recursive: true });
  await writeFile(out, buildIco(images));
  return out;
}

async function write(path, contents) {
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, contents);
  return path;
}

async function generateMobile() {
  const a = (p) => join(MOBILE_DIR, "assets", p);

  return [
    // Icon Composer reads this file from disk, so it is generated too rather than being a
    // hand-kept fourth copy of the artwork.
    await write(a("expo.icon/Assets/torii-check.svg"), FOREGROUND),

    // Vector forms, for anything that wants the mark without rasterising it: press kits,
    // the store listing, a quick look at what changed.
    await write(a("brand/icon-square.svg"), SQUARE),
    await write(a("brand/icon-rounded.svg"), ROUNDED),
    await write(a("brand/mark.svg"), FOREGROUND),

    // `icon` in app.config.ts, and the image the sign-in and paywall screens render.
    await png(SQUARE, 1024, a("images/icon.png")),
    // expo-splash-screen draws this over the canvas colour, so it needs its own corners:
    // a cream torii on the cream canvas would be invisible in light mode.
    await png(ROUNDED, 512, a("images/splash-icon.png")),
    await png(SQUARE, 48, a("images/favicon.png")),
    await png(ANDROID_BACKGROUND, 512, a("images/android-icon-background.png")),
    await png(ANDROID_FOREGROUND, 512, a("images/android-icon-foreground.png")),
    await png(ANDROID_MONOCHROME, 432, a("images/android-icon-monochrome.png")),
  ];
}

async function generateSite() {
  const p = (f) => join(SITE_DIR, "public", f);

  return [
    await png(SQUARE, 16, p("favicon-16x16.png")),
    await png(SQUARE, 32, p("favicon-32x32.png")),
    await png(SQUARE, 48, p("favicon-48x48.png")),
    // iOS masks this itself, so it stays square and opaque.
    await png(SQUARE, 180, p("apple-touch-icon.png")),
    await png(SQUARE, 180, p("apple-icon.png")),
    await png(SQUARE, 192, p("android-chrome-192x192.png")),
    await png(SQUARE, 512, p("android-chrome-512x512.png")),
    await png(MASKABLE, 512, p("android-chrome-maskable-512x512.png")),
    await png(SQUARE, 1024, p("icon.png")),
    // Read off disk by app/opengraph-image.tsx, app/twitter-image.tsx and the JSON-LD
    // Organization logo in app/layout.tsx. Neutral names, so new artwork is a file swap.
    await png(SQUARE, 512, p("site-image-512x512.png")),
    await png(SQUARE, 1024, p("site-image-1024x1024.png")),
    await writeIco([16, 32, 48], p("favicon.ico")),
    // Next's app directory wins over public/favicon.ico, so both have to be the mark.
    await writeIco([16, 32, 48], join(SITE_DIR, "app", "favicon.ico")),
  ];
}

const only = process.argv.slice(2);
const wantMobile = only.length === 0 || only.includes("--mobile");
const wantSite = only.length === 0 || only.includes("--site");

const written = [];
if (wantMobile) written.push(...(await generateMobile()));

if (wantSite) {
  try {
    await readdir(join(SITE_DIR, "public"));
    written.push(...(await generateSite()));
  } catch {
    console.warn(
      `! site repo not found at ${SITE_DIR} — skipped. Set SITE_DIR to override.`,
    );
  }
}

for (const file of written) {
  console.log(
    `  ${file.replace(`${MOBILE_DIR}/`, "").replace(`${SITE_DIR}/`, "site/")}`,
  );
}
console.log(`\n${written.length} files written.`);
