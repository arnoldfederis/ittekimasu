-- Hiragana and katakana, the two decks that have to come before everything else.
--
-- The N5 deck writes its readings in hiragana, so it silently assumes the learner can
-- already read kana. For a beginner that is the wall the app currently starts at. Both
-- decks are FREE for the same reason: this is the first ten minutes of learning Japanese,
-- and putting it behind the paywall would gate the part that earns the subscription.
--
-- Card shape differs from the vocabulary decks on purpose. There is no "reading · meaning"
-- here because a kana IS its reading: front is the character, back is the romaji. Cards
-- carry card_type 'KANA', and the app speaks the FRONT of a card whose back has no reading
-- segment (see lib/speech.ts).
--
-- Coverage per script: 46 base (gojūon) + 25 dakuten/handakuten + 33 yōon = 104 cards.
-- Deliberately NOT included: the katakana long-vowel mark ー and the extended foreign-sound
-- combinations (ファ, ティ, ウェ). They matter for reading menus and loan words, but neither
-- works as a standalone flashcard with a spoken answer.

-- Kana comes first in the learn tab; the JLPT decks shift down to make room.
UPDATE courses
SET sort_order = sort_order + 2,
    updated_at = now()
WHERE topic IN ('JLPT', 'LIVING');

